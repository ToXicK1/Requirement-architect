from requirements_architect.schemas.technology import TechnologySpec


@dataclass(frozen=True)
class StageContext:
    """Everything a design stage may read. Earlier-stage outputs are optional until they exist."""

    project_id: str
    problem_statement: str
    brief: ProjectBrief
    answers: Mapping[str, ClarificationAnswer]
    requirements: RequirementsSpec
    research: ResearchReport | None = None
    architecture: ArchitectureSpec | None = None
    extras: Mapping[str, object] = field(default_factory=dict)


def find_cycles(graph: Mapping[str, Sequence[str]]) -> list[list[str]]:
    """Return one representative path for each cycle found by depth-first search."""
    white, grey, black = 0, 1, 2
    color = dict.fromkeys(graph, white)
    stack: list[str] = []
    cycles: list[list[str]] = []

    def visit(node: str) -> None:
        color[node] = grey
        stack.append(node)
        for nxt in graph[node]:
            if nxt not in color:
                continue
            if color[nxt] == grey:
                cycles.append([*stack[stack.index(nxt) :], nxt])
            elif color[nxt] == white:
                visit(nxt)
        stack.pop()
        color[node] = black

    for n in graph:
        if color[n] == white:
            visit(n)
    return cycles


def render_answers(answers: Mapping[str, ClarificationAnswer]) -> str:
    return "\n".join(f"{a.question_id}: {a.answer}" for a in answers.values()) or "(none)"


def render_requirements(spec: RequirementsSpec) -> str:
    lines = [
        f"{fr.id} [{fr.priority.value}] {fr.name} (actor: {fr.actor}): {fr.description[:220]}"
        for fr in spec.functional
    ]
    for n in spec.nonfunctional:
        target = f" target={n.target} ({n.target_status.value})" if n.target else ""
        lines.append(f"{n.id} [{n.category.value}] {n.statement[:200]}{target}")
    return "\n".join(lines) or "(none)"


def render_findings(report: ResearchReport | None) -> tuple[str, str]:
    if report is None or not report.findings:
        return (
            "no research findings are available; mark anything about external technology as unverified",
            "(none)",
        )
    lines = [
        f"{f.finding_id} [{f.kind.value}, {f.verification.value}] {f.claim[:300]}"
        for f in report.findings
    ]
    return "findings below; only 'verified' facts are confirmed against sources", "\n".join(lines)


def render_architecture(arch: ArchitectureSpec | None) -> str:
    if arch is None:
        return "(none)"
    lines = [f"pattern: {arch.selected_pattern.value}"]
    lines += [
        f"{c.id} {c.name} ({c.kind.value}): {c.responsibility[:160]}" for c in arch.components
    ]
    return "\n".join(lines)


def base_untrusted(ctx: StageContext) -> dict[str, str]:
    """The untrusted blocks every design prompt carries (tag name == key)."""
    note, findings = render_findings(ctx.research)
    return {
        "problem_statement": ctx.problem_statement,
        "brief": ctx.brief.model_dump_json(indent=2),
        "answers": render_answers(ctx.answers),
        "requirements": render_requirements(ctx.requirements),
        "findings": findings,
        "_note": note,
    }


async def run_stage[T: BaseModel](
    gateway: LLMGateway,
    prompt_id: str,
    ctx: StageContext,
    schema: type[T],
    untrusted: Mapping[str, str],
    plain: Mapping[str, str] | None = None,
) -> T:
    """Render a prompt (untrusted blocks delimiter-neutralized) and get validated structured output."""
    prompt = load_prompt(prompt_id)
    values: dict[str, str] = {}
    for key, text in untrusted.items():
        if key == "_note":
            values["evidence_note"] = text  # generated by our code, not user-controlled
        else:
            values[key] = wrap_untrusted(text, key)
    values.update(plain or {})
    system, user = prompt.render(**values)
    request = LLMRequest(
        system=system,
        messages=[Message(role="user", content=user)],
        prompt_id=prompt.id,
        prompt_version=prompt.version,
        project_id=ctx.project_id,
        max_tokens=16000,
    )
    obj, _ = await gateway.complete_structured(request, schema)
    return obj


def render_technology(spec: object) -> str:
    if not isinstance(spec, TechnologySpec):
        return "(none)"
    return "\n".join(f"{t.id} {t.name} ({t.category.value})" for t in spec.technologies) or "(none)"


def render_data_api(spec: object) -> str:
    if not isinstance(spec, DataApiSpec):
        return "(none)"
    lines = [f"{e.id} {e.name}: {', '.join(f.name for f in e.fields)}" for e in spec.entities]
    lines += [
        f"{p.id} {p.method.value} {p.path} (auth: {p.authentication.value}): {p.purpose[:120]}"
        for p in spec.endpoints
    ]
    if spec.interface_note:
        lines.append(f"interface: {spec.interface_note[:300]}")
    return "\n".join(lines) or "(none)"
